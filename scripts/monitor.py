"""Outcome KPIs + monitoring checks on my internship search.

Input (LOCAL, git-ignored): data/tracker/applications.csv -- my own plain table,
one row per application, that I fill in myself (never generated by an AI). It can
be an export of my "Candidatures PFE" Google Sheet as long as it has these columns:
    date_applied, company, title, offer_id, source, country, status, date_response, notes
Status values: sent, callback, interview, rejected, offer, withdrawn (French
equivalents envoyée / rappel / entretien / refus / proposition / abandon work too).

Outputs (committed, aggregates only -- no company name, no title):
    docs/data/outcomes.json        current outcome KPIs + current check results
    docs/data/monitoring_log.json  one line per run, so the dashboard shows that the
                                   checks really ran, and what they caught each time

The four checks ("something is wrong with my search" means, for me):
  1. STALE      an application sent more than STALE_DAYS ago with no answer yet -> follow up
  2. FRESHNESS  the weekly France Travail fetch is older than 8 days -> the workflow stopped
  3. NEW_MATCH  no new high-match offer since the previous run -> widen the search
  4. BACKLOG    high-match offers I have not applied to yet -> review them

    python3 scripts/monitor.py
"""
import csv
import json
import os
import statistics
import time
from datetime import date, datetime

TRACKER = "data/tracker/applications.csv"
TEMPLATE = "data/tracker/applications.template.csv"
MATCHES = "docs/data/matches.json"
OUTCOMES = "docs/data/outcomes.json"
LOG = "docs/data/monitoring_log.json"
CRITIQUE = "data/quality/critique_log.csv"   # my manual check of the LLM output (committed: France Travail ids only)
STALE_DAYS = 10
FRESHNESS_DAYS = 8

STATUS_MAP = {
    "sent": "sent", "envoyée": "sent", "envoyee": "sent", "en attente": "sent", "relancée": "sent", "relancee": "sent",
    "callback": "callback", "rappel": "callback", "rappelé": "callback", "contacté": "callback",
    "interview": "interview", "entretien": "interview",
    "rejected": "rejected", "refus": "rejected", "refusé": "rejected", "refusée": "rejected",
    "offer": "offer", "proposition": "offer", "accepté": "offer", "acceptée": "offer",
    "withdrawn": "withdrawn", "abandon": "withdrawn", "abandonné": "withdrawn",
}
RESPONDED = {"callback", "interview", "rejected", "offer"}
POSITIVE = {"callback", "interview", "offer"}


def parse_date(s):
    """Accepts 2026-09-15, 2026-09-15T08:00:00Z (ISO) and 15/09/2026 or 15/09/26 (Google Sheets FR)."""
    s = (s or "").strip()
    candidates = [(s[:10], "%Y-%m-%d"), (s, "%d/%m/%Y"), (s, "%d/%m/%y")]
    for value, fmt in candidates:
        try:
            return datetime.strptime(value, fmt).date()
        except ValueError:
            continue
    return None


def load_tracker():
    if not os.path.exists(TRACKER):
        print(f"{TRACKER} not found -- copy {TEMPLATE} to it and fill it in. Outcome KPIs will be empty.")
        return []
    with open(TRACKER, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    apps = []
    for r in rows:
        d = parse_date(r.get("date_applied"))
        if not d or "example" in (r.get("company") or "").lower():
            continue
        apps.append({**r, "date_applied": d, "date_response": parse_date(r.get("date_response")),
                     "status": STATUS_MAP.get((r.get("status") or "sent").strip().lower(), "sent")})
    return apps


def load_json(path, default):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def load_critique():
    """Human-in-the-loop check of the extraction: I re-read some offers and log,
    per offer, how many extracted skills I checked and how many were wrong
    (missed, invented, or a soft skill / task instead of a tool)."""
    if not os.path.exists(CRITIQUE):
        return None
    with open(CRITIQUE, encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if (r.get("offer_id") or "").strip()]
    if not rows:
        return None
    checked = sum(int(r.get("skills_checked") or 0) for r in rows)
    errors = sum(int(r.get("errors") or 0) for r in rows)
    types = {}
    for r in rows:
        t = (r.get("error_type") or "").strip()
        if t and int(r.get("errors") or 0):
            types[t] = types.get(t, 0) + int(r.get("errors") or 0)
    return {"n_offers_checked": len({r["offer_id"] for r in rows}), "skills_checked": checked,
            "errors": errors, "error_rate": round(errors / checked, 3) if checked else None, "by_type": types}


def main():
    today = date.today()
    apps = load_tracker()
    matches = load_json(MATCHES, {})
    log = load_json(LOG, {"runs": []})
    prev = log["runs"][-1] if log["runs"] else None

    # ---------------- outcome KPIs
    n = len(apps)
    by_status = {s: sum(1 for a in apps if a["status"] == s) for s in ["sent", "callback", "interview", "rejected", "offer", "withdrawn"]}
    active = [a for a in apps if a["status"] != "withdrawn"]
    responded = [a for a in active if a["status"] in RESPONDED]
    days_to_answer = [(a["date_response"] - a["date_applied"]).days for a in responded if a["date_response"]]
    by_country = {}
    for a in apps:
        c = (a.get("country") or "France").strip() or "France"
        by_country[c] = by_country.get(c, 0) + 1
    by_week = {}
    for a in apps:
        wk = a["date_applied"].isocalendar()
        key = f"{wk[0]}-W{wk[1]:02d}"
        by_week[key] = by_week.get(key, 0) + 1

    # ---------------- checks
    stale = [a for a in active if a["status"] == "sent" and (today - a["date_applied"]).days > STALE_DAYS]
    fetched = matches.get("fetched_at")
    fetched_d = parse_date(fetched) if fetched else None
    fetch_age = (today - fetched_d).days if fetched_d else None
    thr = matches.get("high_match_threshold", 0.4)
    high_ids = sorted(o["id"] for o in matches.get("offers", []) if o.get("score", 0) >= thr)
    prev_ids = set(prev.get("high_match_ids", [])) if prev else set()
    new_high = [i for i in high_ids if i not in prev_ids] if prev else high_ids
    applied_ids = {(a.get("offer_id") or "").strip() for a in apps}
    backlog = [i for i in high_ids if i not in applied_ids]

    checks = [
        {"id": "stale", "label": f"Applications with no answer after {STALE_DAYS} days",
         "value": len(stale), "alert": len(stale) > 0, "action": "Send a follow-up e-mail"},
        {"id": "freshness", "label": "Days since the last France Travail fetch",
         "value": fetch_age, "alert": fetch_age is None or fetch_age > FRESHNESS_DAYS,
         "action": "Check the weekly workflow in the Actions tab"},
        {"id": "new_match", "label": "New high-match offers since the previous check",
         "value": len(new_high), "alert": prev is not None and len(new_high) == 0,
         "action": "Widen the keywords or the region"},
        {"id": "backlog", "label": "High-match offers not applied to yet",
         "value": len(backlog), "alert": len(backlog) > 0, "action": "Review them in the ranking"},
    ]

    outcomes = {
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "n_applications": n,
        "by_status": by_status,
        "response_rate": round(len(responded) / len(active), 3) if active else None,
        "positive_rate": round(sum(1 for a in active if a["status"] in POSITIVE) / len(active), 3) if active else None,
        "median_days_to_answer": statistics.median(days_to_answer) if days_to_answer else None,
        "n_answers_with_date": len(days_to_answer),
        "by_country": by_country,
        "by_week": [{"week": k, "applications": v} for k, v in sorted(by_week.items())],
        "stale_days": STALE_DAYS,
        "checks": checks,
        "critique": load_critique(),
    }
    os.makedirs("docs/data", exist_ok=True)
    with open(OUTCOMES, "w", encoding="utf-8") as f:
        json.dump(outcomes, f, indent=2, ensure_ascii=False)

    log["runs"].append({
        "run_at": outcomes["generated_at"],
        "n_applications": n,
        "n_offers": matches.get("n_offers", 0),
        "checks": {c["id"]: {"value": c["value"], "alert": c["alert"]} for c in checks},
        "high_match_ids": high_ids,     # France Travail ids only (public data); needed for check 3
    })
    with open(LOG, "w", encoding="utf-8") as f:
        json.dump(log, f, indent=2, ensure_ascii=False)

    # ---------------- console report (company names stay here, on my screen)
    print(f"Applications: {n}  |  response rate: {outcomes['response_rate']}  |  by status: {by_status}")
    for c in checks:
        print(f"  [{'ALERT' if c['alert'] else ' ok  '}] {c['label']}: {c['value']}" + (f"  -> {c['action']}" if c["alert"] else ""))
    for a in stale:
        print(f"      follow up: {a.get('company')} -- {a.get('title')} (sent {a['date_applied']}, {(today - a['date_applied']).days} days ago)")
    print(f"\nWrote {OUTCOMES} and appended run #{len(log['runs'])} to {LOG} (aggregates only)")


if __name__ == "__main__":
    main()
